/** Case-insensitive prefix/substring match on Ukrainian or English name. */
export function searchCountries(q: string): Country[] {
  const s = q.trim().toLowerCase();
  if (!s) return COUNTRIES;
  return COUNTRIES.filter(
    (c) => c.uk.toLowerCase().includes(s) || c.en.toLowerCase().includes(s),
  );
}
