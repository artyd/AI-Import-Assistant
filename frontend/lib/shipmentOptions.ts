// Incoterms that apply only to sea / inland-waterway transport.
export const SEA_ONLY_INCOTERMS = new Set(["FAS", "FOB", "CFR", "CIF"]);

/** Transport modes valid for the given Incoterm (sea-only terms restrict to water). */
export function transportOptionsFor(incoterm: string): Option[] {
  if (SEA_ONLY_INCOTERMS.has(incoterm)) {
    return TRANSPORT_MODES.filter((m) => m.value === "sea" || m.value === "inland_waterway");
  }
  return TRANSPORT_MODES;
}

