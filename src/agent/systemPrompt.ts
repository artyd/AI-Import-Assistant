/**
 * System prompt for "Штурман" — the single import-logistics agent (ADR-0001).
 * The rules prefix is frozen (identical for every shipment and turn → one
 * prompt-cache entry); per-shipment state (number, contract mode, documents
 * digest) is a trailing block AFTER the cache breakpoint.
 */
export function buildSystemPrompt(workspace: {
  number: string;
  supplier: string;
  contract_type?: 'bilateral' | 'trilateral' | null;
  contract_type_source?: 'sidebar' | 'survey' | 'auto' | null;
  contract_type_confidence?: number | null;
  survey_status?: string | null;
  /** The shipment's parties card (sender / intermediary / recipient). */
  parties?: { role: string; company_name: string }[];
  /** Compact per-document key-field digest (durable context; see documentsDigest.ts). */
  documentsDigest?: string;
}): ChatSystem {
  const rules = shipmentRules();
  const shipment = [
    `ПОТОЧНЕ ПОСТАЧАННЯ: №${workspace.number}` +
      (workspace.supplier ? `, постачальник: ${workspace.supplier}.` : '.'),
    ...contractModeBlock(workspace),
    ...documentsDigestBlock(workspace.documentsDigest),
  ].join('\n');
  return [
    { type: 'text', text: rules, cache_control: { type: 'ephemeral' } },
    { type: 'text', text: shipment },
  ];
}

/**
 * Durable per-document context: already-extracted key fields. A MEMORY AID, not a
 * source of truth — verdicts still come from the deterministic tools.
 */
function documentsDigestBlock(digest?: string): string[] {
  if (!digest || !digest.trim()) return [];
  return [
    '',
    'ДОКУМЕНТИ ПОСТАЧАННЯ (витяг ключових полів, довідково, оновлюється автоматично):',
    digest,
    'Просте питання (вага, кількість, Incoterms, сторони, номери, дати) — відповідай одразу з «ФАКТИ ПОСТАВКИ», ' +
      'назвавши файл і сторінку звідти. «конфлікт» чи «немає даних» там — читай файли (read_file) перед відповіддю. ' +
      'Комплектність і розбіжності — лише детермінованими інструментами.',
  ];
}

