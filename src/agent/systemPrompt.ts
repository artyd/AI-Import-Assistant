/**
 * Per-shipment contract-structure block (2 vs 3 parties) — part of the trailing
 * dynamic state, so the cacheable rules prefix stays frozen.
 */
function contractModeBlock(ws: {
  contract_type?: 'bilateral' | 'trilateral' | null;
  contract_type_source?: 'sidebar' | 'survey' | 'auto' | null;
  contract_type_confidence?: number | null;
  survey_status?: string | null;
  parties?: { role: string; company_name: string }[];
}): string[] {
  // Real names from the shipment's parties card; the importer is NOT always the same company.
  const nameOf = (role: string, fallback: string): string =>
    ws.parties?.find((p) => p.role === role && p.company_name.trim())?.company_name.trim() ?? fallback;
  const sender = nameOf('sender', 'постачальник');
  const intermediary = nameOf('intermediary', 'посередник');
  const recipient = nameOf('recipient', 'покупець-імпортер');
  const modeUk =
    ws.contract_type === 'bilateral'
      ? `двосторонній (${sender} → ${recipient})`
      : ws.contract_type === 'trilateral'
        ? `тристоронній (${sender} → ${intermediary} → ${recipient})`
        : 'не визначено';
  const srcUk =
    ws.contract_type_source === 'sidebar' || ws.contract_type_source === 'survey'
      ? 'встановлено вручну (НЕ перезаписуй автоматично)'
      : ws.contract_type_source === 'auto'
        ? 'автовизначено з документів'
        : 'не задано';
  const conf =
    typeof ws.contract_type_confidence === 'number'
      ? ` (впевненість ${Math.round(ws.contract_type_confidence * 100)}%)`
      : '';
  const survey =
    ws.survey_status && ws.survey_status !== 'not_started' ? ` Опитування: ${ws.survey_status}.` : '';
  return [
    '',
    `СТРУКТУРА КОНТРАКТУ: ${modeUk}; джерело: ${srcUk}${conf}.${survey}`,
    '- Тристоронній: посередник купує в постачальника й перепродає імпортеру — два плеча, два контракти,',
    '  різні ціни, нерідко однаковий номер інвойсу. Імпортера бери зі сторін постачання, не з памʼяті.',
    '- Режим не визначено або потрібен для аналізу — get_contract_mode (рахує за документами), не «на око».',
    '- Зберігай через set_contract_mode: source="survey", коли користувач підтвердив у розмові; source="auto" —',
    '  автовисновок (не перезаписує ручне). Пріоритет: ручний вибір > підтвердження користувача > авто.',
    '- Опитування пропонуй рідко: лише коли режим не вдалося визначити або впевненість низька.',
  ];
}

